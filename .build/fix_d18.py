def patch(path, pairs, name):
    t = io.open(path, encoding="utf-8").read()
    for old, new, exp, lab in pairs:
        n = t.count(old)
        if n != exp:
            log.append("  MISS [%s/%s] 期望%d 实际%d" % (name, lab, exp, n))
            continue
        t = t.replace(old, new)
        log.append("  OK   [%s/%s] x%d" % (name, lab, n))
    io.open(path, "w", encoding="utf-8", newline="\n").write(t)


