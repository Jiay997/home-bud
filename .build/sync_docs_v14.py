rep = []


def patch(path, pairs):
    t = io.open(path, encoding="utf-8").read()
    for old, new, exp, lab in pairs:
        n = t.count(old)
        if n != exp:
            rep.append("  MISS [%s] 期望%d 实际%d | %s" % (lab, exp, n, old[:60].replace("\n", " ")))
            continue
        t = t.replace(old, new)
        rep.append("  OK   [%s] x%d" % (lab, n))
    io.open(path, "w", encoding="utf-8", newline="\n").write(t)
    rep.append("-- %s 行数 %d" % (os.path.basename(path), t.count("\n") + 1))


