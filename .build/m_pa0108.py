def nav(active, role='内容运营', todo=('待审 2', '举报 1')):
    rows = [('b', '家伴 · 后台', 'v1.0'), ('sep',)]
    for key, label in NAV_ITEMS:
        rows.append(('t', ('● ' if key == active else '○ ') + label))
    rows += [('sep',), ('t', '待办 %d' % len(todo))]
    for t in todo:
        rows.append(('t', '  ' + t))
    rows += [('sep',), ('t', '角色 · ' + role), ('t', '环境 · 生产')]
    return rows


def blocks(nav_rows, main_rows):
    """左右两栏等高拼接，返回外层框的 raw 行"""
    nl = box(nav_rows, NAV_W)
    ml = box(main_rows, MAIN_W)
    if len(nl) < len(ml):
        filler = ['│' + ' ' * (NAV_W - 2) + '│'] * (len(ml) - len(nl))
        nl = nl[:-1] + filler + nl[-1:]
    elif len(ml) < len(nl):
        filler = ['│' + ' ' * (MAIN_W - 2) + '│'] * (len(nl) - len(ml))
        ml = ml[:-1] + filler + ml[-1:]
    return [('raw', l) for l in side(nl, ml, gap=0)]


def page(main_rows, active, role='内容运营', todo=('待审 2', '举报 1'), user='admin01'):
    top_l = '家伴 · 后台管理端'
    top_r = '管理员 %s｜角色：%s｜环境：生产　[退出]' % (user, role)
    return ([('b', top_l, top_r), ('sep',)] +
            blocks(nav(active, role, todo), main_rows))


def split_page(left_rows, right_rows, top_l, top_r, lw=42, rw=32):
    """左右两块并排（PA-01 登录页用）"""
    ll = box(left_rows, lw)
    rl = box(right_rows, rw)
    return [('b', top_l, top_r), ('sep',)] + \
        [('raw', l) for l in side(ll, rl, gap=0)]


