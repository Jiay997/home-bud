# ---------------------------------------------------------------- 排版工具
def ck(s, limit=LIMIT):
    """显示宽度校验，超宽直接报错（开发期快速定位）"""
    if dw(s) > limit:
        raise AssertionError('overflow %d>%d: %r' % (dw(s), limit, s))
    return s


def cell(s, w):
    if dw(s) > w:
        raise AssertionError('cell %d>%d: %r' % (dw(s), w, s))
    return pad(s, w)


def ln(*parts):
    """把 (文本, 列宽) 元组或裸字符串拼成一行"""
    out = []
    for p in parts:
        out.append(cell(p[0], p[1]) if isinstance(p, tuple) else p)
    return ''.join(out)


def T(cells, widths):
    """主内容区表格行"""
    return ('t', ck(ln(*[(c, w) for c, w in zip(cells, widths)])))


def RULE(n=None):
    return ('t', '─' * (n or LIMIT))


def nest(rows, w=48, indent=1):
    """缩进包装的嵌套框（库内无 nest，按模板自定义）"""
    return [('raw', ' ' * indent + l) for l in box(rows, w)]


