def nav(active):
    rows = [('c', '家伴 · 后台'), ('sep',)]
    for i, item in enumerate(NAV):
        rows.append(('t', ('* ' if i == active else '  ') + item))
    rows.append(('blank',))
    rows.append(('sep',))
    rows.append(('t', '角色：内容运营'))
    rows.append(('raw', '[ 退出登录 ]'))
    return box(rows, 24)


def content(rows, title=None, w=68):
    return box(rows, w, title)


def grid(headers, widths, rows):
    """对齐的表格行（返回 box 行列表）"""
    out = [('t', ''.join(pad(h, wd) for h, wd in zip(headers, widths)))]
    out.append(('raw', ' ' + '-' * (sum(widths) - 1)))
    for r in rows:
        out.append(('t', ''.join(pad(str(c), wd) for c, wd in zip(r, widths))))
    return out


