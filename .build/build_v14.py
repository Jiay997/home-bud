def rep(old, new, expect=1, label=""):
    global t
    n = t.count(old)
    if n != expect:
        report.append("MISS  [%s] 期望 %d 实际 %d | %s" % (label, expect, n, old[:70].replace("\n", " ")))
        return
    t = t.replace(old, new)
    report.append("OK    [%s] x%d" % (label, n))


def rex(pat, new, expect=1, label="", flags=re.S):
    global t
    n = len(re.findall(pat, t, flags))
    if n != expect:
        report.append("MISS  [%s] 期望 %d 实际 %d | %s" % (label, expect, n, pat[:70]))
        return
    t = re.sub(pat, new, t, count=expect, flags=flags)
    report.append("OK    [%s] x%d" % (label, n))


